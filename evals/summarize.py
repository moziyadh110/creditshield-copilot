"""Mean and spread over the repeated eval runs:  uv run python -m evals.summarize

Reads the latest `repeated_runs` full-set results per prompt version and mode from
evals/results/<mode>/ and writes evals/results/summary.md. Spread is the sample standard
deviation, with the min-max range beside it. Count targets show the worst run, because the
gate requires them on every run.
"""

import json
import statistics
from collections import defaultdict

from app.llmops.gate import load_targets
from evals.runner import RESULTS_DIR

MODES = {"e2e": "end to end", "generation": "generation only"}
EXTRA = ["sent_rate_expected_send", "total_cost_usd", "judge_cost_usd"]


def latest_runs(n: int) -> dict[tuple[str, int], list[dict]]:
    runs = defaultdict(list)
    for mode in MODES:
        for path in sorted((RESULTS_DIR / mode).glob("v*.json")):
            r = json.loads(path.read_text(encoding="utf-8"))
            if r["full_set"]:
                runs[(mode, r["prompt_version"])].append(r)
    return {k: sorted(v, key=lambda r: r["created"])[-n:] for k, v in runs.items()}


def _unit(name: str):
    if name.endswith("_usd"):
        return lambda x: f"${x:.5f}" if x < 0.01 else f"${x:.4f}"
    if name == "latency_ms":
        return lambda x: f"{x / 1000:.1f} s"
    return lambda x: f"{x:.3g}"


def cell(name: str, values: list[float], kind: str | None) -> str:
    if kind == "count":
        return f"{max(values):g} on every run" if len(set(values)) == 1 else f"max {max(values):g}"
    f = _unit(name)
    mean = statistics.fmean(values)
    sd = statistics.stdev(values) if len(values) > 1 else 0.0
    return f"{f(mean)} ± {f(sd)} ({f(min(values))}–{f(max(values))})"


def summary_markdown() -> str:
    targets = load_targets()
    n = targets["repeated_runs"]
    runs = latest_runs(n)
    versions = sorted({v for _, v in runs})
    lines = [
        "# Eval summary: mean ± sd (min–max) over the repeated runs",
        "",
        "Generated by `uv run python -m evals.summarize` from evals/results/.",
        "",
    ]
    for mode, label in MODES.items():
        counts = ", ".join(f"v{v}: {len(runs.get((mode, v), []))} runs" for v in versions)
        lines += [f"## {label.capitalize()} ({counts})", ""]
        lines += ["| Metric | Target | " + " | ".join(f"v{v}" for v in versions) + " |"]
        lines += ["| --- | --- |" + " --- |" * len(versions)]
        names = [k for k in targets["targets"] if k != "retrieval_hit_rate"] + EXTRA
        for name in names:
            t = targets["targets"].get(name, {})
            rule = f"{t['op']} {t['value']:g}" if "op" in t else "report"
            row = []
            for v in versions:
                values = [r["metrics"][name] for r in runs.get((mode, v), [])]
                values = [x for x in values if x is not None]
                row.append(cell(name, values, t.get("kind")) if values else "n/a")
            lines.append(f"| {name} | {rule} | " + " | ".join(row) + " |")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    text = summary_markdown()
    (RESULTS_DIR / "summary.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
